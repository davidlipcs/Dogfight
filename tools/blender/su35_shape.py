def wing_le(x):
    x = np.asarray(x, float)
    return np.where(x < 2.50, 0.10, 0.10 - (x - 2.50) * TAN_LE)


def wing_te(x):
    x = np.asarray(x, float)
    return -5.79 - (x - 2.50) * (6.13 - 5.79) / (X_WTIP - 2.50)


def wing_z(x):
    return Z_WING + 0.0 * np.asarray(x, float)


