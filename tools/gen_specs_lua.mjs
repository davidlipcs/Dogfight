// Writes roblox/src/shared/sim/SpecData.luau from web/js/specs.js (the evaluated data: aircraft, missiles, radars ...).
//   node tools/gen_specs_lua.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const S = await import(path.join(here, '..', 'web', 'js', 'specs.js'));

const NAMES = { ru: ['R-73', 'R-77'], se: ['IRIS-T', 'Meteor'], uk: ['ASRAAM', 'Meteor'], fr: ['MICA IR', 'MICA EM'], cn: ['PL-10', 'PL-15'] };
const data = {
  IR: S.IR, ARH: S.ARH, MISSILES: S.MISSILES, PLAYER_MISSILES: S.PLAYER_MISSILES, BANDIT_MISSILES: S.BANDIT_MISSILES,
  AIRCRAFT: S.AIRCRAFT, TRAINERS: S.TRAINERS, BANDITS: S.BANDITS, PLANE_GROUPS: S.PLANE_GROUPS, WEAPON_CLASS: S.WEAPON_CLASS, NAMES,
  LINER: S.LINER,
};

const isIdent = (k) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while'].includes(k);
function lua(v, ind) {
  if (v === undefined || v === null) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : (v > 0 ? 'math.huge' : '-math.huge');
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  const pad = '\t'.repeat(ind + 1), end = '\t'.repeat(ind);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x === 'number' || typeof x === 'string')) return '{ ' + v.map((x) => lua(x, ind)).join(', ') + ' }';
    return '{\n' + v.map((x) => pad + lua(x, ind + 1)).join(',\n') + '\n' + end + '}';
  }
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  const parts = keys.map((k) => {
    const key = /^\d+$/.test(k) ? `[${k}]` : isIdent(k) ? k : `[${JSON.stringify(k)}]`;
    return `${pad}${key} = ${lua(v[k], ind + 1)}`;
  });
  return '{\n' + parts.join(',\n') + '\n' + end + '}';
}
const out = `--!nonstrict
-- GENERATED by tools/gen_specs_lua.mjs from web/js/specs.js - do not edit by hand.
-- The aircraft, missile, radar, gun and countermeasure data of the game (arrays are 1-based, station numbers are keys).
return ${lua(data, 0)}
`;
const dest = path.join(here, '..', 'roblox', 'src', 'shared', 'sim', 'SpecData.luau');
fs.writeFileSync(dest, out);
console.log('wrote', dest, out.length, 'chars');
