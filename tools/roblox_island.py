#!/usr/bin/env python3
"""Turns the game's island (web/assets/terrain.json + terrain_color.jpg) into Luau data modules for the Roblox version: the
exact 1025 x 1025 height grid of the game (the simulation flies over it, the terrain is built from it) and the ground
material of every grid point.   python3 tools/roblox_island.py
  roblox/src/shared/IslandH01..17.luau  heights: base64 of the raw int16 grid (units of `scale` metres), 64 rows each
  roblox/src/shared/IslandM1..7.luau    ground material digits (1 grass, 2 leafy grass, 3 ground, 4 rock, 5 sand, 6 snow)
  roblox/src/shared/Island.luau         the numbers"""
import array
import base64
import glob
import json
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "roblox", "src", "shared")
H_ROWS, M_ROWS = 64, 150
CODES = {"grass": 1, "leafy": 2, "ground": 3, "rock": 4, "sand": 5, "snow": 6}


def main():
    d = json.load(open(os.path.join(ROOT, "web", "assets", "terrain.json")))
    res, scale = d["res"], d["scale"]
    n = res + 1
    raw = array.array("h")
    raw.frombytes(base64.b64decode(d["heights"]))
    grid = np.array(raw, dtype=np.int16).reshape(n, n)                    # [row (y, from the south)][col (x, from the west)]
    metres = grid.astype(np.float32) * scale
    color = np.asarray(Image.open(os.path.join(ROOT, "web", "assets", "terrain_color.jpg")).convert("RGB"), dtype=np.float32)
    H, W = color.shape[:2]
    # the colour at every grid point (the picture's top row is the north edge: v is flipped)
    px = np.clip(np.round(np.arange(n) / (n - 1) * (W - 1)).astype(int), 0, W - 1)
    py = np.clip(np.round((1 - np.arange(n) / (n - 1)) * (H - 1)).astype(int), 0, H - 1)
    rgb = color[py][:, px]                                                # [row][col][3]
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mx, mn = rgb.max(axis=2), rgb.min(axis=2)
    sat = (mx - mn) / (mx + 1e-6)
    mats = np.full((n, n), CODES["leafy"], dtype=np.uint8)
    mats[mx >= 108] = CODES["grass"]
    dry = (r >= g * 0.92) & (g > 110)
    mats[dry] = CODES["ground"]
    mats[dry & (mx > 175)] = CODES["sand"]
    mats[(sat < 0.16) & (mx > 60)] = CODES["rock"]
    mats[(metres > 1500) & (sat < 0.22) & (mx > 175)] = CODES["snow"]
    mats[metres <= 0] = CODES["sand"]                                     # the sea bed
    for f in glob.glob(os.path.join(OUT, "IslandH*.luau")) + glob.glob(os.path.join(OUT, "IslandM*.luau")):
        os.remove(f)
    hnames, mnames = [], []
    for k, r0 in enumerate(range(0, n, H_ROWS)):
        chunk = grid[r0:r0 + H_ROWS].astype("<i2").tobytes()
        name = "IslandH%02d" % (k + 1)
        hnames.append(name)
        with open(os.path.join(OUT, name + ".luau"), "w") as fh:
            fh.write('--!nonstrict\n-- GENERATED by tools/roblox_island.py: heights, rows %d..%d (base64 of int16 little endian)\nreturn "%s"\n' % (r0, min(r0 + H_ROWS, n) - 1, base64.b64encode(chunk).decode()))
    for k, r0 in enumerate(range(0, n, M_ROWS)):
        digits = "".join(str(int(v)) for v in mats[r0:r0 + M_ROWS].flatten())
        name = "IslandM%d" % (k + 1)
        mnames.append(name)
        with open(os.path.join(OUT, name + ".luau"), "w") as fh:
            fh.write('--!nonstrict\n-- GENERATED by tools/roblox_island.py: ground materials, rows %d..%d\nreturn "%s"\n' % (r0, min(r0 + M_ROWS, n) - 1, digits))
    a = d["airfield"]
    with open(os.path.join(OUT, "Island.luau"), "w") as fh:
        fh.write("""--!nonstrict
-- GENERATED by tools/roblox_island.py: the game's island (the height grid of web/assets/terrain.json).
return {
	size = %.1f,                 -- the side of the island (metres)
	res = %d,                    -- cells per side (the grid has res + 1 points per side)
	scale = %s,                  -- metres per height unit of the raw grid
	HeightRows = %d,             -- rows per IslandH module
	MatRows = %d,                -- rows per IslandM module
	HeightModules = { %s },
	MatModules = { %s },
	airfield = { x = %.1f, y = %.1f, elevation = %.1f },     -- the home air base (metres, the game's frame: +y is north)
}
""" % (d["size"], res, scale, H_ROWS, M_ROWS, ", ".join('"%s"' % x for x in hnames), ", ".join('"%s"' % x for x in mnames), a["x"], a["y"], a["elevation"]))
    cnt = {k: int((mats == v).sum()) for k, v in CODES.items()}
    print("island %dx%d points, %d height modules, %d material modules, materials %s" % (n, n, len(hnames), len(mnames), cnt))


if __name__ == "__main__":
    main()
