#!/usr/bin/env python3
"""Turns the game's island (web/assets/terrain.json + terrain_color.jpg) into Luau data modules for the Roblox version:
roblox/src/shared/IslandH1..3.luau (the heights, base64), IslandM.luau (the ground material of every cell, one digit)
and Island.luau (the numbers).  The Roblox terrain is built from them by IslandBuilder.luau.   python3 tools/roblox_island.py"""
import array
import base64
import json
import math
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 384                       # the Roblox island is a grid of N x N cells
OFFSET = 300.0                # metres added before the heights are packed as uint16 (units of 0.25 m)
CODES = {"grass": 1, "leafy": 2, "ground": 3, "rock": 4, "sand": 5, "snow": 6}


def main():
    d = json.load(open(os.path.join(ROOT, "web", "assets", "terrain.json")))
    res, scale, size = d["res"], d["scale"], d["size"]
    raw = array.array("h")
    raw.frombytes(base64.b64decode(d["heights"]))
    n = res + 1
    grid = (np.array(raw, dtype=np.float32) * scale).reshape(n, n)       # [gj][gi], metres
    color = np.asarray(Image.open(os.path.join(ROOT, "web", "assets", "terrain_color.jpg")).convert("RGB"), dtype=np.float32)
    H, W = color.shape[:2]

    # the N x N sample points (cell centres), in the game's frame: i along x, j along y (north)
    idx = (np.arange(N) + 0.5) / N
    gi = idx * (n - 1)
    gj = idx * (n - 1)
    heights = np.zeros((N, N), dtype=np.float32)
    mats = np.zeros((N, N), dtype=np.uint8)
    step = (n - 1) / N
    for j in range(N):
        y0 = int(j * step)
        y1 = max(y0 + 1, int((j + 1) * step))
        for i in range(N):
            x0 = int(i * step)
            x1 = max(x0 + 1, int((i + 1) * step))
            heights[j, i] = grid[y0:y1, x0:x1].mean()
    # the colour at each cell (v is flipped: the picture's top row is the north edge)
    px = np.clip((idx * (W - 1)).astype(int), 0, W - 1)
    py = np.clip(((1 - idx) * (H - 1)).astype(int), 0, H - 1)
    for j in range(N):
        for i in range(N):
            r, g, b = color[py[j], px[i]]
            h = heights[j, i]
            mx, mn = max(r, g, b), min(r, g, b)
            sat = (mx - mn) / (mx + 1e-6)
            if h <= 0:
                m = "sand"                                       # the sea bed (under water anyway)
            elif h > 1500 and sat < 0.22 and mx > 175:
                m = "snow"
            elif sat < 0.16 and mx > 60:
                m = "rock"
            elif r >= g * 0.92 and g > 110:
                m = "sand" if mx > 175 else "ground"             # the dry, yellowish patches
            elif mx >= 108:
                m = "grass"
            else:
                m = "leafy"
            mats[j, i] = CODES[m]
    np.save(os.path.join(ROOT, "roblox", "tools", "island_mats.npy"), mats)
    Image.fromarray((mats * 40).astype(np.uint8)).resize((768, 768)).transpose(Image.FLIP_TOP_BOTTOM).save(os.path.join(ROOT, "roblox", "tools", "island_mats_preview.png"))
    Image.fromarray(np.clip((heights + 220) / 4700 * 255, 0, 255).astype(np.uint8)).resize((768, 768)).transpose(Image.FLIP_TOP_BOTTOM).save(os.path.join(ROOT, "roblox", "tools", "island_height_preview.png"))

    # heights as uint16 little endian (units of 0.25 m, +OFFSET), 3 modules of N/3 rows
    packed = np.clip(np.round((heights + OFFSET) / 0.25), 0, 65535).astype("<u2")
    rows_per = N // 3
    out = os.path.join(ROOT, "roblox", "src", "shared")
    for k in range(3):
        chunk = packed[k * rows_per:(k + 1) * rows_per].tobytes()
        s = base64.b64encode(chunk).decode()
        with open(os.path.join(out, "IslandH%d.luau" % (k + 1)), "w") as f:
            f.write("--!nonstrict\n-- GENERATED by tools/roblox_island.py: rows %d..%d of the island's heights (base64, uint16 little endian)\nreturn \"%s\"\n" % (k * rows_per, (k + 1) * rows_per - 1, s))
    digits = "".join(str(int(v)) for v in mats.flatten())
    with open(os.path.join(out, "IslandM.luau"), "w") as f:
        f.write("--!nonstrict\n-- GENERATED by tools/roblox_island.py: the ground material of every cell (1 grass, 2 leafy grass, 3 ground, 4 rock, 5 sand, 6 snow)\nreturn \"%s\"\n" % digits)
    a = d["airfield"]
    with open(os.path.join(out, "Island.luau"), "w") as f:
        f.write("""--!nonstrict
-- GENERATED by tools/roblox_island.py: the game's island as a grid for the Roblox terrain.
return {
	N = %d,                      -- cells per side
	SizeMeters = %.1f,           -- the island's side in the game (metres)
	Offset = %.1f,               -- metres added to the heights before packing
	Unit = 0.25,                 -- metres per height unit
	HeightRows = %d,             -- rows in each of IslandH1..3
	MinHeight = %.1f,
	MaxHeight = %.1f,
	Airfield = { x = %.1f, y = %.1f, elevation = %.1f },   -- the home air base (metres, the game's frame: y is north)
	RunwayLength = 3000, RunwayWidth = 45,
}
""" % (N, size, OFFSET, rows_per, float(heights.min()), float(heights.max()), a["x"], a["y"], a["elevation"]))
    cnt = {k: int((mats == v).sum()) for k, v in CODES.items()}
    print("island %dx%d cells (%.0f m each), height %.0f..%.0f m, materials %s" % (N, N, size / N, heights.min(), heights.max(), cnt))


if __name__ == "__main__":
    main()
