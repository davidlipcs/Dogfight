"""Writes web/js/skins.js and roblox/src/shared/Catalog.luau from tools/skins_data.py.  python3 tools/gen_skins.py"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from skins_data import AIR, PILOT, PRICE, RARITY  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
assert len(AIR) == 100 and len(PILOT) == 10, (len(AIR), len(PILOT))
for ids in ([r[0] for r in AIR], [r['id'] for r in PILOT]):
    assert len(set(ids)) == len(ids), "duplicate id"


def air_obj(r):
    i, name, color, pat, pcol, metal, rough, glow, rar = r
    return {"id": "a_" + i, "name": name, "price": PRICE[rar], "rarity": rar, "color": color, "emissive": glow, "metal": metal, "rough": rough,
            "pattern": pat, "pcolor": pcol}


def pilot_obj(r):
    o = {"id": "p_" + r["id"], "name": r["name"], "price": {"C": 600, "R": 2500, "E": 4500, "L": 8000}[r["rarity"]], "rarity": r["rarity"]}
    for k, v in r.items():
        if k not in ("id", "name", "rarity"):
            o[k] = v
    o.setdefault("mirror", False)
    o.setdefault("pressure", False)
    return o


air = [air_obj(r) for r in AIR]
pilot = [pilot_obj(r) for r in PILOT]


def js_val(v):
    if v is None:
        return "null"
    return json.dumps(v, ensure_ascii=False)


def js_rows(rows, hexkeys):
    out = []
    for o in rows:
        parts = []
        for k, v in o.items():
            parts.append("%s: %s" % (k, "0x%06x" % v if k in hexkeys else js_val(v)))
        out.append("  { " + ", ".join(parts) + " },")
    return "\n".join(out)


js = """// GENERATED by tools/gen_skins.py from tools/skins_data.py - do not edit by hand.
// 100 paint schemes for the jets and 10 elaborate flight outfits for the pilot (the shop sells both for credits).
export const RARITY = %s;
export const AIR_SKINS = [
%s
];
export const PILOT_SKINS = [
%s
];
""" % (json.dumps(RARITY, ensure_ascii=False), js_rows(air, {"color", "emissive", "pcolor"}), js_rows(pilot, {"suit", "suit2", "helmet", "helmet2", "visor", "accent", "glove"}))
with open(os.path.join(ROOT, "web", "js", "skins.js"), "w", encoding="utf-8") as f:
    f.write(js)


def lua_val(v):
    if v is None:
        return "nil"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    return str(v)


def lua_rows(rows, hexkeys):
    out = []
    for o in rows:
        parts = []
        for k, v in o.items():
            if v is None:
                continue
            parts.append("%s = %s" % (k, "0x%06X" % v if k in hexkeys else lua_val(v)))
        out.append("\t{ " + ", ".join(parts) + " },")
    return "\n".join(out)


luau = """--!nonstrict
-- GENERATED by tools/gen_skins.py from tools/skins_data.py - do not edit by hand.
-- 100 paint schemes for the jets and 10 elaborate flight outfits for the pilot.
export type AirSkin = { id: string, name: string, price: number, rarity: string, color: number, emissive: number, metal: number?, rough: number?, pattern: string?, pcolor: number }
export type PilotSkin = { id: string, name: string, price: number, rarity: string, desc: string, suit: number, suit2: number, helmet: number, helmet2: number, pattern: string, visor: number, visorT: number, mirror: boolean, accent: number, glove: number, callsign: string, patch: string, pressure: boolean }

local Catalog = {}

Catalog.Rarity = %s

Catalog.Air = {
%s
}

Catalog.Pilot = {
%s
}

Catalog.AirById = {}
Catalog.PilotById = {}
for _, s in Catalog.Air do Catalog.AirById[s.id] = s end
for _, s in Catalog.Pilot do Catalog.PilotById[s.id] = s end

return Catalog
""" % ("{ " + ", ".join("%s = %s" % (k, json.dumps(v, ensure_ascii=False)) for k, v in RARITY.items()) + " }",
       lua_rows(air, {"color", "emissive", "pcolor"}), lua_rows(pilot, {"suit", "suit2", "helmet", "helmet2", "visor", "accent", "glove"}))
os.makedirs(os.path.join(ROOT, "roblox", "src", "shared"), exist_ok=True)
with open(os.path.join(ROOT, "roblox", "src", "shared", "Catalog.luau"), "w", encoding="utf-8") as f:
    f.write(luau)
print("wrote", len(air), "aircraft skins and", len(pilot), "pilot outfits")
