"""Renders the procedural sounds of web/js/audio.js (the same formulas) into ONE wav file (a "sound sheet": every sound has its own
place in it) and writes roblox/src/shared/SoundMap.luau with where each one is.  One upload to Roblox is enough.
  python3 tools/make_roblox_sounds.py        -> roblox/audio/dogfight_sounds.wav + roblox/src/shared/SoundMap.luau
Needs numpy."""
import math
import os
import wave

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATE = 22050
GAP = 0.3

seed = [1]


def noise_array(n):
    out = np.empty(n)
    s = seed[0]
    for i in range(n):
        s = (s * 16807) % 2147483647
        out[i] = s / 1073741823.5 - 1
    seed[0] = s
    return out


def lowpass(x, k, state=0.0):
    out = np.empty_like(x)
    lp = state
    for i, v in enumerate(x):
        lp += (v - lp) * k
        out[i] = lp
    return out, lp


def tt(seconds):
    return np.arange(int(RATE * seconds)) / RATE


S = {}                                          # name -> (samples, loop)
lp1 = lp2 = 0.0


def lpn(k, n):
    """low-passed noise (the audio.js `lp` / `lp2` filters share their state between sounds: here every sound starts from rest)"""
    y, _ = lowpass(noise_array(n), k)
    return y


def loopable(x, fade=0.06):
    """a noise loop made seamless: the start is cross-faded with the part that follows the end"""
    n = int(RATE * fade)
    L = len(x) - n
    w = np.linspace(0, 1, n)
    y = x[:L].copy()
    y[:n] = x[:n] * np.sqrt(w) + x[L:L + n] * np.sqrt(1 - w)
    return y


def add(name, x, loop=False):
    S[name] = (np.clip(x, -1, 1), loop)


n2 = int(RATE * 2.06)
add("engine", loopable(lpn(0.08, n2) * 3.2), True)
add("afterburner", loopable(lpn(0.35, n2) * 1.6), True)
t = tt(1)
add("whine", 0.18 * np.sin(2 * np.pi * 900 * t) + 0.08 * np.sin(2 * np.pi * 1830 * t) + 0.05 * noise_array(len(t)), True)
t = tt(0.5)
ph = (t * 100) % 1
add("gun", np.where(ph < 0.45, 1, 0.35) * noise_array(len(t)) * 0.9, True)
t = tt(1)
add("growl", 0.35 * (0.55 + 0.45 * np.sin(2 * np.pi * 20 * t)) * (np.sin(2 * np.pi * 400 * t) + 0.5 * np.sin(2 * np.pi * 800 * t) + 0.25 * np.sin(2 * np.pi * 1200 * t)), True)
add("lock_tone", 0.4 * np.sin(2 * np.pi * 1600 * t), True)
add("rwr_lock", np.where((t * 4) % 1 < 0.5, 0.4 * np.sin(2 * np.pi * 1000 * t), 0), True)
add("rwr_launch", 0.4 * np.sin(2 * np.pi * np.where((t * 12) % 1 < 0.5, 1100, 1500) * t), True)
add("wind", loopable(lpn(0.12, n2) * 2.4), True)
add("flyby", loopable(lpn(0.2, n2) * 2.6), True)
add("whoosh", loopable(lpn(0.5, int(RATE * 1.06)) * 1.4), True)
# one-shots
t = tt(0.35)
add("rwr_new", np.where((t * 10) % 1 < 0.5, 0.4 * np.sin(2 * np.pi * 1200 * t), 0))
t = tt(1.6)
add("launch", lpn(0.25, len(t)) * 2.2 * np.exp(-t * 1.6) * np.minimum(1, t * 30))
t = tt(0.25)
add("hit", noise_array(len(t)) * np.exp(-t * 18))
t = tt(2.5)
add("explosion", lpn(0.05, len(t)) * 6 * np.exp(-t * 1.5) * np.minimum(1, t * 80))
t = tt(1.4)
add("boom", (lpn(0.06, len(t)) * 7 + 0.6 * np.sin(2 * np.pi * 38 * t)) * np.exp(-t * 3.2) * np.minimum(1, t * 400))
t = tt(0.7)
f = np.where(t < 0.18, 880, 1320)
t0 = np.where(t < 0.18, t, t - 0.18)
add("splash", 0.3 * np.sin(2 * np.pi * f * t) * np.exp(-t0 * 5))
t = tt(1.1)
f = np.where(t < 0.15, 784, np.where(t < 0.3, 988, 1175))
t0 = np.where(t < 0.15, t, np.where(t < 0.3, t - 0.15, t - 0.3))
add("medal", 0.28 * (np.sin(2 * np.pi * f * t) + 0.3 * np.sin(4 * np.pi * f * t)) * np.exp(-t0 * 4))

# the sheet
pos = 0.5
chunks, rows = [np.zeros(int(RATE * pos))], []
for name, (x, loop) in S.items():
    rows.append((name, pos, len(x) / RATE, loop))
    chunks.append(x)
    gap = np.zeros(int(RATE * GAP))
    chunks.append(gap)
    pos += len(x) / RATE + GAP
sheet = np.concatenate(chunks)
sheet = sheet / max(1e-9, np.abs(sheet).max()) * 0.9
os.makedirs(os.path.join(ROOT, "roblox", "audio"), exist_ok=True)
path = os.path.join(ROOT, "roblox", "audio", "dogfight_sounds.wav")
with wave.open(path, "wb") as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(RATE)
    w.writeframes((sheet * 32767).astype("<i2").tobytes())
lua = ["--!nonstrict",
       "-- GENERATED by tools/make_roblox_sounds.py: where each sound of roblox/audio/dogfight_sounds.wav is (seconds).  Upload that one file to",
       "-- Roblox (see roblox/README.md) and put its asset id into Config.SoundId, or into the attribute SoundAssetId of ReplicatedStorage.",
       "return {"]
for name, start, length, loop in rows:
    lua.append('\t%s = { start = %.3f, length = %.3f, loop = %s },' % (name, start, length, "true" if loop else "false"))
lua.append("}")
with open(os.path.join(ROOT, "roblox", "src", "shared", "SoundMap.luau"), "w") as f:
    f.write("\n".join(lua) + "\n")
print("wrote %s: %.1f s, %d KB, %d sounds" % (path, len(sheet) / RATE, os.path.getsize(path) // 1024, len(rows)))
